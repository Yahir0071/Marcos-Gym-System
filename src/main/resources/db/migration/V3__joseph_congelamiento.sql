BEGIN;

CREATE TABLE IF NOT EXISTS solicitudes_congelamiento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    socio_id BIGINT NOT NULL REFERENCES socios(id),
    membresia_id BIGINT NOT NULL REFERENCES membresias(id),
    dias_solicitados INTEGER NOT NULL,
    fecha_inicio_solicitada DATE NOT NULL,
    motivo VARCHAR(300) NOT NULL,
    estado VARCHAR(20) NOT NULL,
    fecha_solicitud TIMESTAMP NOT NULL,
    CHECK (estado IN ('PENDIENTE', 'APROBADA', 'RECHAZADA'))
);

CREATE INDEX IF NOT EXISTS idx_congelamiento_socio_fecha
    ON solicitudes_congelamiento (socio_id, fecha_solicitud DESC);

COMMIT;
