BEGIN;

CREATE TABLE IF NOT EXISTS rutina_dias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL,
    vigente_desde DATE NOT NULL,
    dia INTEGER NOT NULL CHECK (dia BETWEEN 1 AND 7),
    sesion VARCHAR(100) NOT NULL,
    descripcion VARCHAR(4000) NOT NULL,
    UNIQUE (username, vigente_desde, dia)
);

CREATE TABLE IF NOT EXISTS entrenamiento_registros (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL,
    fecha DATE NOT NULL,
    UNIQUE (username, fecha)
);

ALTER TABLE rutina_dias ENABLE ROW LEVEL SECURITY;
ALTER TABLE entrenamiento_registros ENABLE ROW LEVEL SECURITY;
ALTER TABLE solicitudes_congelamiento ENABLE ROW LEVEL SECURITY;

ALTER TABLE solicitudes_congelamiento
    ADD COLUMN IF NOT EXISTS fecha_resolucion TIMESTAMP,
    ADD COLUMN IF NOT EXISTS resuelto_por VARCHAR(255);

CREATE INDEX IF NOT EXISTS idx_congelamiento_membresia_estado
    ON solicitudes_congelamiento (membresia_id, estado);
CREATE INDEX IF NOT EXISTS idx_congelamiento_estado_fecha
    ON solicitudes_congelamiento (estado, fecha_solicitud DESC);

