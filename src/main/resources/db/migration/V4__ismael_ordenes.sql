BEGIN;

CREATE TABLE IF NOT EXISTS ordenes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    referencia VARCHAR(60) NOT NULL UNIQUE,
    socio_id BIGINT NOT NULL REFERENCES socios(id),
    tipo_concepto VARCHAR(15) NOT NULL,
    estado_pago VARCHAR(15) NOT NULL,
    estado_entrega VARCHAR(40),
    stock_reservado BOOLEAN NOT NULL DEFAULT FALSE,
    plan_id BIGINT,
    duracion_dias INTEGER,
    reserva_id BIGINT,
    comprador_nombre VARCHAR(511) NOT NULL,
    comprador_doc_tipo VARCHAR(15) NOT NULL,
    comprador_doc_num VARCHAR(15) NOT NULL,
    comprador_email VARCHAR(255) NOT NULL,
    card_brand VARCHAR(12),
    card_last4 VARCHAR(4),
    total DOUBLE PRECISION NOT NULL,
    fecha TIMESTAMP NOT NULL,
    demo BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS orden_detalles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden_id BIGINT NOT NULL REFERENCES ordenes(id),
    producto_id BIGINT,
    nombre VARCHAR(512) NOT NULL,
    categoria VARCHAR(40),
    imagen_url VARCHAR(255),
    precio_unitario DOUBLE PRECISION NOT NULL,
    cantidad INTEGER NOT NULL CHECK (cantidad > 0)
);

CREATE INDEX IF NOT EXISTS idx_ordenes_socio_fecha ON ordenes (socio_id, fecha DESC);
CREATE INDEX IF NOT EXISTS idx_ordenes_reserva_estado ON ordenes (reserva_id, estado_pago);
CREATE INDEX IF NOT EXISTS idx_orden_detalles_orden ON orden_detalles (orden_id);

ALTER TABLE ordenes ENABLE ROW LEVEL SECURITY;
ALTER TABLE orden_detalles ENABLE ROW LEVEL SECURITY;

COMMIT;
